function txt=yaw_report(rows,c)
txt=sprintf(['yaw 是实际偏航角，角度统一换算为度后与 %g°目标比较；', ...
    '这里统计无外力工况的偏航阶跃响应，不等于测试了偏航外力矩抗扰。', ...
    '各方案共用姿态环，所以此表也用于检查位置控制改动后是否影响姿态响应。\n\n', ...
    '| 方案 | 超调率 / %% | 10–90%%上升时间 / s | 2%%调节时间 / s | 无扰尾段RMS / ° | 无扰尾段峰峰值 / ° |\n', ...
    '| --- | ---: | ---: | ---: | ---: | ---: |\n'],c.yaw_target_deg);
for j=1:numel(rows)
    v=rows(j);
    txt=[txt sprintf('| %s | %s | %s | %s | %s | %s |\n',md(char(v.scheme)), ...
        num(get_scalar(v,'overshoot_percent'),4),num(get_scalar(v,'rise_10_90_s'),4,'未达到'), ...
        num(get_scalar(v,'settling_2pct_s'),4,'未调节'), ...
        num(get_scalar(v,'nominal_tail_rms_error_deg'),6), ...
        num(get_scalar(v,'nominal_tail_peak_to_peak_deg'),6))]; %#ok<AGROW>
end
txt=[txt sprintf(['\n调节时间从 %g s 阶跃起算，误差带为 ±%g°，持续性检查至 %g s。', ...
    '尾段使用 %g–%g s；显示为0.000000仅表示当前小数位分辨率下很小，完整值见CSV。\n\n'], ...
    c.yaw_step,.02*abs(c.yaw_target_deg),c.metric_end,c.tail_window(1),c.tail_window(2))];
end

function txt=solver_report(checks,models,labels,c,coarse_rows)
txt=sprintf(['控制器采样周期保持 %g s，机体求解步长由 %g s 减半到 %g s。', ...
    '下表只列实际保存在结果中的场景检查；轨迹差指细步长轨迹与主步长轨迹插值后的最大绝对差。\n\n', ...
    '| 方案 | 场景 | x最大差 / mm | y最大差 / mm | z最大差 / mm |\n', ...
    '| --- | --- | ---: | ---: | ---: |\n'],c.controller_sample,c.main_step,c.fine_step);
count=0;
for j=1:numel(checks)
    ck=checks(j);
    if ~isfield(ck,'scenarios') || isempty(ck.scenarios),continue;end
    name='未标注模型';
    if isfield(ck,'model')
        name=char(ck.model);ii=find(strcmp(models,name),1);
        if ~isempty(ii),name=labels{ii};end
    end
    for q=1:numel(ck.scenarios)
        sc=ck.scenarios(q);
        if ~isfield(sc,'max_xyz_difference_m'),continue;end
        d=sc.max_xyz_difference_m;
        if numel(d)~=3,continue;end
        scen='未标注场景';
        if isfield(sc,'scenario')
            names={'无扰动','仅x外力','仅y外力','仅z外力'};
            if isscalar(sc.scenario) && any(sc.scenario==0:3),scen=names{sc.scenario+1};end
        end
        txt=[txt sprintf('| %s | %s | %s | %s | %s |\n', ...
            md(name),scen,mm(d(1)),mm(d(2)),mm(d(3)))]; %#ok<AGROW>
        count=count+1;
    end
end
if count==0,txt=[txt sprintf('| 无可识别的轨迹差记录 | — | — | — | — |\n')];end
have_fine=false;
for j=1:numel(checks)
    if isfield(checks(j),'fine_metrics') && ~isempty(checks(j).fine_metrics),have_fine=true;break;end
end
if have_fine
    txt=[txt sprintf(['\n| 轴 | 方案 | 主步长扰动峰值 / mm | 半步长扰动峰值 / mm | 主步长尾段RMS / mm | 半步长尾段RMS / mm |\n', ...
        '| --- | --- | ---: | ---: | ---: | ---: |\n'])];
    for j=1:numel(checks)
        ck=checks(j);
        if ~isfield(ck,'fine_metrics') || isempty(ck.fine_metrics) || ~isfield(ck,'model'),continue;end
        model=char(ck.model);ii=find(strcmp(models,model),1);
        if isempty(ii),name=model;else,name=labels{ii};end
        for q=1:numel(ck.fine_metrics)
            f=ck.fine_metrics(q);
            if ~isfield(f,'channel'),continue;end
            channel=char(f.channel);
            ind=find(strcmp({coarse_rows.model},model)&strcmp({coarse_rows.channel},channel),1);
            if isempty(ind),continue;end
            co=coarse_rows(ind);
            txt=[txt sprintf('| %s | %s | %s | %s | %s | %s |\n',channel,md(name), ...
                mm(co.disturbance_peak_m),mm(get_scalar(f,'disturbance_peak_m')), ...
                mm(co.nominal_tail_rms_error_m),mm(get_scalar(f,'nominal_tail_rms_error_m')))]; %#ok<AGROW>
        end
    end
end
txt=[txt sprintf(['\n若不同步长下存在明显幅值或相位变化，尤其持续振荡的配对扰动指标变化明显时，', ...
    '不能把小数末位差异用于性能排名。减半步长检验只反映数值一致性，不等于已经证明算法稳定或实机鲁棒。', ...
    '主图统一展示主步长结果，复核结果用于判断可信范围。\n\n'])];
end

function v=find_row(rows,model,channel)
i=find(strcmp({rows.model},model)&strcmp({rows.channel},channel));
assert(numel(i)==1,'模型 %s 的 %s 轴应有且只有一条指标。',model,channel);
v=rows(i);
end

function val=get_scalar(s,field)
if isfield(s,field) && isnumeric(s.(field)) && isscalar(s.(field))
    val=s.(field);
else
    val=NaN;
end
end

function a=as_cellstr(a)
if isstring(a),a=cellstr(a);elseif ischar(a),a={a};end
assert(iscell(a),'模型和标签必须是字符串或字符元胞数组。');
a=cellfun(@char,a,'UniformOutput',false);
end

function s=num(x,d,missing)
if nargin<3,missing='—';end
if isempty(x) || ~isscalar(x) || ~isfinite(x),s=missing;else,s=sprintf(['%.' num2str(d) 'f'],x);end
end

function s=mm(x)
if ~isfinite(x),s='—';elseif x>=0 && x*1000<.001,s='<0.001';else,s=sprintf('%.3f',1000*x);end
end

function s=md(s)
s=strrep(char(s),'|','\|');
s=regexprep(s,'[\r\n]+',' ');
end

function write_struct_csv(path,rows)
% 手动写 UTF-8 BOM，避免部分 Excel 版本按本地 ANSI 编码误读中文。
fields=fieldnames(rows);
for j=1:numel(fields)
    assert(all(double(fields{j})<128),'CSV 字段名必须为 ASCII：%s',fields{j});
end
lines=cell(numel(rows)+1,1);
lines{1}=strjoin(fields.',',');
for i=1:numel(rows)
    vals=cell(1,numel(fields));
    for j=1:numel(fields)
        x=rows(i).(fields{j});
        if isnumeric(x) || islogical(x)
            if isempty(x),s='';elseif isscalar(x),s=sprintf('%.17g',double(x));else,s=jsonencode(x);end
        elseif ischar(x) || isstring(x)
            s=char(x);
        else
            s=jsonencode(x);
        end
        vals{j}=['"' strrep(s,'"','""') '"'];
    end
    lines{i+1}=strjoin(vals,',');
end
body=[strjoin(lines,sprintf('\r\n')) sprintf('\r\n')];
fid=fopen(path,'wb');assert(fid~=-1,'无法写入 %s',path);
clean=onCleanup(@()fclose(fid)); %#ok<NASGU>
fwrite(fid,uint8([239 187 191]),'uint8');
fwrite(fid,unicode2native(body,'UTF-8'),'uint8');
end

function save_text(path,body)
fid=fopen(path,'w','n','UTF-8');assert(fid~=-1,'无法写入 %s',path);
clean=onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid,'%s',body);
end
