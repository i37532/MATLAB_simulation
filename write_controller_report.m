function write_controller_report(outdir, manifest)
%WRITE_CONTROLLER_REPORT 由本次实际仿真指标生成中文报告和 UTF-8 CSV。
% write_controller_report(outdir, manifest)
% 必需字段：labels、models、metrics、config。
% 可选字段：yaw_metrics、solver_checks。所有数值直接取自 manifest。
% CSV 使用 ASCII 字段名、UTF-8 BOM，方便 Excel 直接打开。

assert(isstruct(manifest) && isfield(manifest,'metrics') && isfield(manifest,'config'), ...
    'manifest 必须包含 metrics 和 config。');
assert(~isempty(manifest.metrics),'没有可报告的 XYZ 指标。');
if ~exist(outdir,'dir'), mkdir(outdir); end
datadir=fullfile(outdir,'data');
if ~exist(datadir,'dir'), mkdir(datadir); end
r=manifest.metrics;
labels=as_cellstr(manifest.labels);
models=as_cellstr(manifest.models);
assert(numel(labels)==numel(models),'labels 和 models 的数量不同。');
c=manifest.config;
channels={'x','y','z'};
required={'starts','targets','stop_time','force','force_on','force_off', ...
    'metric_end','tail_window','recovery_bands','recovery_min_duration', ...
    'main_step','fine_step','controller_sample','yaw_step','yaw_target_deg','pwm_limits'};
for j=1:numel(required)
    assert(isfield(c,required{j}),'config 缺少字段：%s',required{j});
end
write_struct_csv(fullfile(datadir,'xyz_metrics.csv'),r);
has_yaw=isfield(manifest,'yaw_metrics') && ~isempty(manifest.yaw_metrics);
if has_yaw, write_struct_csv(fullfile(datadir,'yaw_metrics.csv'),manifest.yaw_metrics); end

step_table=sprintf(['| 轴 | 方案 | 超调率 / %% | 10–90%%上升时间 / s | 2%%调节时间 / s | 23–25 s最大误差 / mm | 配对扰动峰值 / mm | 恢复时间 / s |\n', ...
    '| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: |\n']);
tail_table=sprintf(['| 轴 | 方案 | 无扰尾段RMS / mm | 无扰尾段峰峰值 / mm | 无扰尾段最大绝对误差 / mm | 有扰绝对误差峰值 / mm | 有扰绝对误差RMS / mm |\n', ...
    '| --- | --- | ---: | ---: | ---: | ---: | ---: |\n']);
integral_table=sprintf(['| 轴 | 方案 | 阶跃窗口RMSE / m | 阶跃窗口IAE / (m·s) | 配对扰动IAE / (m·s) |\n', ...
    '| --- | --- | ---: | ---: | ---: |\n']);
for k=1:3
    for m=1:numel(models)
        v=find_row(r,models{m},channels{k});
        step_table=[step_table sprintf('| %s | %s | %s | %s | %s | %s | %s | %s |\n', ...
            channels{k},md(labels{m}),num(v.overshoot_percent,4), ...
            num(v.rise_10_90_s,4,'未达到'),num(v.settling_2pct_s,4,'未调节'), ...
            mm(v.tail_max_error_m),mm(v.disturbance_peak_m), ...
            num(v.disturbance_recovery_s,4,'未恢复'))]; %#ok<AGROW>
        tail_table=[tail_table sprintf('| %s | %s | %s | %s | %s | %s | %s |\n', ...
            channels{k},md(labels{m}),mm(v.nominal_tail_rms_error_m), ...
            mm(v.nominal_tail_peak_to_peak_m),mm(v.nominal_tail_max_abs_error_m), ...
            mm(v.disturbed_absolute_peak_error_m),mm(v.disturbed_absolute_rms_error_m))]; %#ok<AGROW>
        integral_table=[integral_table sprintf('| %s | %s | %s | %s | %s |\n', ...
            channels{k},md(labels{m}),num(v.nominal_rmse_m,6), ...
            num(v.nominal_iae_m_s,6),num(v.disturbance_iae_m_s,6))]; %#ok<AGROW>
    end
end
definitions=sprintf([ ...
    '- 超调率先按目标方向统一符号，再以阶跃幅值归一化，因此 z 的负目标不会导致符号误判。10–90%%上升时间取响应首次跨越两个阈值的时间差。\n', ...
    '- 2%%调节时间从各轴阶跃时刻起算：x/y 的误差带为 ±%g/±%g m，z 为 ±%g m，要求进入后直到 %g s 不再越界。“未调节”表示观察窗口内未满足条件。\n', ...
    '- 23–25 s最大误差只描述该窗口，不能代表之后已收敛。无扰尾段统计使用 %g–%g s，RMS 为误差平方的时间平均值再开方，峰峰值为窗口最大值减最小值。\n', ...
    '- 配对扰动误差 = 同一方案有扰动位置 − 无扰动位置；峰值及 IAE 使用 %g–%g s。有扰绝对误差 = 有扰动位置 − 目标位置。\n', ...
    '- 恢复时间从 %g s 撤去外力后起算，x/y/z 误差带分别为 ±%g、±%g、±%g mm；入带后需保持到 %g s，且至少有 %g s 带内记录。“未恢复”表示未满足该标准；0 表示撤去外力时已在带内且随后保持，并不表示误差瞬间归零。不同轴的恢复阈值不同，不能直接跨轴排名。\n', ...
    '- 阶跃窗口为各轴阶跃时刻至 %g s。RMSE 衡量整体误差幅度，IAE 是绝对误差的时间积分；二者都包含跟踪目标的过渡过程。\n', ...
    '- 表格中小于 0.001 mm 的非负误差显示为“<0.001”，并非数学上等于零。CSV 保留完整数值；NaN 表示观察窗口内指标未满足或不可定义。\n'], ...
    .02*abs(c.targets(1)),.02*abs(c.targets(2)),.02*abs(c.targets(3)),c.metric_end, ...
    c.tail_window(1),c.tail_window(2),c.force_on,c.stop_time, ...
