txt=[txt sprintf(['\n比较代码统一目标、机体参数、扰动和电机输出边界；各方案内部的控制结构与参数保留。', ...
    '因此横向差异可能同时来自算法、增益和前馈/抗饱和适配。原PID和最早原STA保留水平速度误差的±1限幅，另外三组保留不限幅设置；最终电机PWM约束则对五组一致。', ...
